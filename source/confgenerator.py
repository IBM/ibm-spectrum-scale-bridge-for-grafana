import cherrypy
import io
import shutil
import socket
import os
import re
import tarfile
try:
    # Optional dependency
    import yaml
except ImportError as e:
    yaml = e
from messages import MSG, ERR
import analytics


if not isinstance(yaml, ImportError):
    class MyDumper(yaml.Dumper):

        def ignore_aliases(self, data):
            # Jobs share the same nested dicts; emit them in full instead of &idNNN/*idNNN anchors
            return True

        def increase_indent(self, flow=False, indentless=False):
            return super(MyDumper, self).increase_indent(flow, False)
else:
    class MyDumper(object):
        pass


# Bridge internal metrics jobs: job name -> metrics path
INTERNAL_METRICS_JOBS = {"GrafanaBridgeHttpMetrics": "/http_metrics",
                         "GrafanaBridgeInternalStats": "/internal_stats"}
JOB_SUFFIX_PATTERN = re.compile(r'^[A-Za-z0-9_.:-]{1,64}$')
SCRAPE_CONFIGS_HEADER = ("# Generated by IBM Storage Scale bridge for Grafana.\n"
                         "# Do not edit, changes will be lost on the next update.\n"
                         "# Reference this file in prometheus.yml under scrape_config_files.\n")


class PrometheusConfigGenerator(object):
    exposed = True

    def __init__(self, logger, mdHandler, config_attr, endpoints):
        if isinstance(yaml, ImportError):
            raise yaml
        self.logger = logger
        self.__md = mdHandler
        self.endpoints = endpoints
        self.attr = config_attr

    @property
    def md(self):
        return self.__md

    @property
    def qh(self):
        return self.__md.qh

    @property
    def TOPO(self):
        return self.__md.metaData

    def _detect_outbound_ip(self):
        """Return the local IP used to reach an external host, or None on failure."""
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
                s.connect(('8.8.8.8', 80))
                return s.getsockname()[0]
        except Exception as exc:
            self.logger.warning(MSG['TargetFallbackFailed'].format(exc))
            return None

    def _resolve_target(self, target_param):
        """Return (host, port) for the scrape target.

        Priority:
          1. Explicit target_param (may be 'host' or 'host:port').
          2. promBindIp when it is not a wildcard.
          3. Outbound-route detection.
          4. First IP from hostname resolution.
        """
        prom_port = str(self.attr.get('prometheus'))

        if target_param:
            parts = target_param.rsplit(':', 1)
            host = parts[0]
            port = parts[1] if len(parts) == 2 else prom_port
            return host, port

        bind_ip = self.attr.get('promBindIp', '')
        if bind_ip and bind_ip not in ('0.0.0.0', '::'):
            return bind_ip, prom_port

        # Wildcard bind — detect outbound IP
        self.logger.info(MSG['TargetFallbackDetected'].format(bind_ip))
        ip = self._detect_outbound_ip()
        if ip:
            return ip, prom_port

        # Last resort: hostname resolution
        hostname = socket.getfqdn()
        try:
            ip = socket.gethostbyname_ex(hostname)[2][0]
            self.logger.warning(MSG['TargetFallbackAny'].format(ip))
            return ip, prom_port
        except OSError:
            return hostname, prom_port

    def _tls_cert_paths(self, job_suffix=''):
        """Return (cert_path, key_path) to embed in generated Prometheus configs.
        When *job_suffix* is non-empty the paths are placed in a per-suffix
        subdirectory so that scrape configs generated for multiple clusters
        never reference the same file — preventing one cluster's copy from
        overwriting another's.
        Example (tlsKeyPath=/etc/bridge_ssl/certs, job_suffix=_cluster2):
            cert_path → /etc/bridge_ssl/certs/_cluster2/cert.pem
            key_path  → /etc/bridge_ssl/certs/_cluster2/privkey.pem
        """
        base = self.attr.get('tlsKeyPath')
        cert_file = self.attr.get('tlsCertFile')
        key_file = self.attr.get('tlsKeyFile')
        if job_suffix:
            # Strip a leading underscore/dot from the suffix to form a clean
            # directory name (e.g. "_cluster2" → "cluster2").
            subdir = job_suffix.lstrip('_.')
            base = os.path.join(base, subdir)
        return os.path.join(base, cert_file), os.path.join(base, key_file)

    def _copy_certs(self, dest_dir, job_suffix=''):
        """Copy the bridge TLS cert and key into *dest_dir*.
        When *job_suffix* is non-empty the files are copied into a per-suffix
        subdirectory of *dest_dir*, matching the paths generated by
        ``_tls_cert_paths``.
        Raises cherrypy.HTTPError(500) on I/O failure.
        """
        src_cert = os.path.join(self.attr.get('tlsKeyPath'),
                                self.attr.get('tlsCertFile'))
        src_key = os.path.join(self.attr.get('tlsKeyPath'),
                               self.attr.get('tlsKeyFile'))
        if job_suffix:
            subdir = job_suffix.lstrip('_.')
            dest_dir = os.path.join(dest_dir, subdir)
        try:
            os.makedirs(dest_dir, exist_ok=True)
            shutil.copy2(src_cert, dest_dir)
            shutil.copy2(src_key, dest_dir)
            self.logger.info(MSG['CertFilesCopied'].format(dest_dir))
        except OSError as exc:
            self.logger.error(MSG['CertFilesCopyError'].format(dest_dir, exc))
            raise cherrypy.HTTPError(500, MSG['CertFilesCopyError'].format(dest_dir, exc))

    def _common_job_settings(self, target_param, job_suffix=''):
        """Return the dict fragment shared by all scrape jobs (scheme, TLS, auth, target)."""
        job = {}
        job["scheme"] = self.attr.get('protocol')
        if self.attr.get('protocol') == "https":
            if not (
                self.attr.get('tlsKeyPath')
                and self.attr.get('tlsCertFile')
                and self.attr.get('tlsKeyFile')
            ):
                self.logger.error(MSG['MissingSSLCert'])
                raise cherrypy.HTTPError(500, MSG['MissingSSLCert'])
            certPath, keyPath = self._tls_cert_paths(job_suffix)
            tls = {"cert_file": certPath,
                   "key_file": keyPath,
                   "insecure_skip_verify": True}
            job["tls_config"] = tls
        if self.attr.get('enabled', False):
            if not (
                self.attr.get('username', False)
                and self.attr.get('password', False)
            ):
                self.logger.error(MSG['MissingBasicAuthSettings'])
                raise cherrypy.HTTPError(500, MSG['MissingBasicAuthSettings'])
            basic_auth = {"username": self.attr.get('username')}
            if os.path.isfile(self.attr.get('password')):
                pw = {"password_file": self.attr.get('password')}
            else:
                pw = {"password": self.attr.get('password')}
            basic_auth.update(pw)
            job["basic_auth"] = basic_auth
        host, port = self._resolve_target(target_param)
        job["static_configs"] = [{"targets": [f"{host}:{port}"]}]
        return job

    def build_scrape_jobs(self, job_suffix='', internal_metrics=False, target_param=''):
        """Build and return the list of scrape job dicts."""
        common = self._common_job_settings(target_param, job_suffix)
        scrape_configs = []
        for endpoint, sensor in self.endpoints.items():
            period = self.md.getSensorPeriod(sensor)
            if period > 0:
                scrape_job = {}
                scrape_job["job_name"] = sensor + job_suffix
                scrape_job["scrape_interval"] = f"{max(period, 10)}s"
                scrape_job["honor_timestamps"] = True
                scrape_job["metrics_path"] = endpoint
                scrape_job.update(common)
                scrape_configs.append(scrape_job)
        if internal_metrics:
            if not analytics.http_metrics_enabled:
                self.logger.error(MSG['InternalMetricsDisabled'])
                raise cherrypy.HTTPError(400, MSG['InternalMetricsDisabled'])
            for job_name, metrics_path in INTERNAL_METRICS_JOBS.items():
                internal_job = {}
                internal_job["job_name"] = job_name + job_suffix
                internal_job["scrape_interval"] = "60s"
                internal_job["metrics_path"] = metrics_path
                internal_job.update(common)
                scrape_configs.append(internal_job)
        return scrape_configs

    def generate_prometheus_config(self, job_suffix='', internal_metrics=False, target_param=''):
        """Generate a complete prometheus.yml."""
        scrape_configs = self.build_scrape_jobs(job_suffix, internal_metrics, target_param)
        global_config = {"scrape_interval": "15s",
                         "evaluation_interval": "15s",
                         "query_log_file": "/var/log/prometheus/query.log"}
        storage_config = {"tsdb": [{"out_of_order_time_window": "2d"}]}
        alerting_config = {"alertmanagers": [{"static_configs": [{"targets": None}]}]}
        prometheus_job = {}
        prometheus_job["job_name"] = "prometheus"
        prometheus_job["static_configs"] = [{"targets": ["localhost:9090"]}]
        scrape_configs.insert(0, prometheus_job)
        resp = {"global": global_config,
                "alerting": alerting_config,
                "storage": storage_config,
                "rule_files": None,
                "scrape_configs": scrape_configs}
        yaml_string = yaml.dump(resp, Dumper=MyDumper, default_flow_style=False)
        return yaml_string

    def generate_scrape_jobs_config(self, job_suffix='', internal_metrics=False, target_param=''):
        """Generate a file content for prometheus.yml scrape_config_files, containing only scrape_configs."""
        resp = {"scrape_configs": self.build_scrape_jobs(job_suffix, internal_metrics, target_param)}
        yaml_string = yaml.dump(resp, Dumper=MyDumper, default_flow_style=False)
        return SCRAPE_CONFIGS_HEADER + yaml_string

    def _write_to_path(self, content, path, default_filename='scrape_configs.yml'):
        """Write content to path on the bridge filesystem.
        path may be:
          - an absolute path to an existing writable file  → overwritten
          - an absolute path to an existing writable dir   → default_filename written inside it
          - an absolute path to a non-existing file whose parent dir is writable → file created
        Raises cherrypy.HTTPError(400) for invalid paths and (500) for I/O failures.
        """
        if not os.path.isabs(path):
            self.logger.error(MSG['InvalidPathParam'].format(path))
            raise cherrypy.HTTPError(400, MSG['InvalidPathParam'].format(path))
        if os.path.isdir(path):
            dest = os.path.join(path, default_filename)
        else:
            dest = path
            parent = os.path.dirname(dest)
            if not os.path.isdir(parent):
                self.logger.error(MSG['InvalidPathParam'].format(path))
                raise cherrypy.HTTPError(400, MSG['InvalidPathParam'].format(path))
        try:
            with open(dest, 'w') as f:
                f.write(content)
            self.logger.info(MSG['ScrapeConfigFileWritten'].format(dest))
        except OSError as exc:
            self.logger.error(MSG['ScrapeConfigFileWriteError'].format(dest, exc))
            raise cherrypy.HTTPError(500, MSG['ScrapeConfigFileWriteError'].format(dest, exc))

    def _parse_params(self, params):
        """Validate the query parameters job_suffix, internal_metrics, target and path."""
        job_suffix = params.get('job_suffix', '')
        if not isinstance(job_suffix, str) or (job_suffix and not JOB_SUFFIX_PATTERN.match(job_suffix)):
            self.logger.error(MSG['InvalidJobSuffix'].format(job_suffix))
            raise cherrypy.HTTPError(400, MSG['InvalidJobSuffix'].format(job_suffix))
        internal_metrics = str(params.get('internal_metrics', 'false')).lower()
        if internal_metrics not in ('true', 'false'):
            self.logger.error(MSG['InvalidBooleanParam'].format(internal_metrics, 'internal_metrics'))
            raise cherrypy.HTTPError(400, MSG['InvalidBooleanParam'].format(internal_metrics, 'internal_metrics'))
        target_param = params.get('target', '')
        if target_param:
            parts = target_param.rsplit(':', 1)
            if len(parts) == 2 and not parts[1].isdigit():
                self.logger.error(MSG['InvalidTargetParam'].format(target_param))
                raise cherrypy.HTTPError(400, MSG['InvalidTargetParam'].format(target_param))
            if not parts[0]:
                self.logger.error(MSG['InvalidTargetParam'].format(target_param))
                raise cherrypy.HTTPError(400, MSG['InvalidTargetParam'].format(target_param))
        path_param = params.get('path', '')
        return job_suffix, internal_metrics == 'true', target_param, path_param

    def GET(self, **params):
        '''Handle the requests:
           /prometheus.yml - complete prometheus configuration file
           /scrape_configs.yml - content for a file referenced in prometheus.yml under scrape_config_files
           Optional query parameters:
           job_suffix       - string appended to the scrape job names
           internal_metrics - true|false, add scrape jobs for /http_metrics and /internal_stats (default false)
           target           - override the scrape target: <host> or <host>:<port>
                              When omitted the bridge auto-detects its outbound IP (option B).
                              When only <host> is given the configured prometheus port is used.
           path             - absolute path on the bridge filesystem to write the config to.
                              If path is a directory, prometheus.yml or scrape_configs.yml
                              is written inside it depending on the endpoint.
                              When the bridge is running HTTPS, the TLS cert and key are also
                              copied into the same directory (in a per-suffix subdirectory when
                              job_suffix is set), matching the paths generated in tls_config.
                              Use this when Prometheus runs on the same host as the bridge.
                              For a remote Prometheus host, use GET /tls_certs instead.
        '''
        self.logger.trace(f"Request headers:{str(cherrypy.request.headers)}")
        conn = cherrypy.request.headers.get('Host').split(':')
        if len(conn) == 2 and int(conn[1]) != int(self.attr.get('prometheus')):
            self.logger.error(MSG['EndpointNotSupportedForPort'].
                              format(cherrypy.request.script_name, str(conn[1])))
            raise cherrypy.HTTPError(400, ERR[400])

        if cherrypy.request.script_name == '/prometheus.yml':
            generate = self.generate_prometheus_config
        elif cherrypy.request.script_name == '/scrape_configs.yml':
            generate = self.generate_scrape_jobs_config
        else:
            self.logger.error(MSG['EndpointNotSupported'].format(cherrypy.request.script_name))
            raise cherrypy.HTTPError(400, ERR[400])

        job_suffix, internal_metrics, target_param, path_param = self._parse_params(params)
        resp = generate(job_suffix, internal_metrics, target_param)
        if path_param:
            default_filename = 'prometheus.yml' if cherrypy.request.script_name == '/prometheus.yml' \
                else 'scrape_configs.yml'
            self._write_to_path(resp, path_param, default_filename)
            if self.attr.get('protocol') == 'https':
                dest_dir = path_param if os.path.isdir(path_param) \
                    else os.path.dirname(path_param)
                self._copy_certs(dest_dir, job_suffix)
        cherrypy.response.headers['Content-Type'] = 'text/plain'
        return resp

    def OPTIONS(self):
        # print('options_post')
        del cherrypy.response.headers['Allow']
        cherrypy.response.headers['Access-Control-Allow-Methods'] = 'GET, POST, NEW, OPTIONS'
        cherrypy.response.headers['Access-Control-Allow-Origin'] = '*'
        cherrypy.response.headers['Access-Control-Allow-Headers'] = 'Content-Type,Accept'
        cherrypy.response.headers['Access-Control-Max-Age'] = 604800


class TlsCertsServer(object):
    exposed = True

    def __init__(self, logger, config_attr):
        self.logger = logger
        self.attr = config_attr

    def _validate_tls_config(self):
        """Raise cherrypy.HTTPError(503) when TLS is not fully configured."""
        if (self.attr.get('protocol') != 'https'
                or not self.attr.get('tlsKeyPath')
                or not self.attr.get('tlsCertFile')
                or not self.attr.get('tlsKeyFile')):
            self.logger.error(MSG['TlsCertsMissingConfig'])
            raise cherrypy.HTTPError(503, MSG['TlsCertsMissingConfig'])

    def _parse_job_suffix(self, params):
        """Validate and return job_suffix from query params."""
        job_suffix = params.get('job_suffix', '')
        if not isinstance(job_suffix, str) or (job_suffix and not JOB_SUFFIX_PATTERN.match(job_suffix)):
            self.logger.error(MSG['InvalidJobSuffix'].format(job_suffix))
            raise cherrypy.HTTPError(400, MSG['InvalidJobSuffix'].format(job_suffix))
        return job_suffix

    def _build_archive(self, job_suffix):
        """Return a bytes object containing the .tar.gz archive.
        Archive members use forward-slash paths regardless of the host OS so
        that ``tar -xz`` on a Linux Prometheus host always works correctly.
        """
        src_cert = os.path.join(self.attr.get('tlsKeyPath'),
                                self.attr.get('tlsCertFile'))
        src_key = os.path.join(self.attr.get('tlsKeyPath'),
                               self.attr.get('tlsKeyFile'))

        # Archive-internal names use forward slashes (tar convention).
        if job_suffix:
            subdir = job_suffix.lstrip('_.')
            arc_cert = f"{subdir}/{self.attr.get('tlsCertFile')}"
            arc_key = f"{subdir}/{self.attr.get('tlsKeyFile')}"
        else:
            arc_cert = self.attr.get('tlsCertFile')
            arc_key = self.attr.get('tlsKeyFile')

        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode='w:gz') as tar:
            tar.add(src_cert, arcname=arc_cert)
            tar.add(src_key, arcname=arc_key)
        return buf.getvalue()

    def GET(self, **params):
        """Return a .tar.gz archive of the bridge TLS cert and key.
        Optional query parameters:
          job_suffix  — when set, files are placed in a matching subdirectory
                        inside the archive (e.g. cluster2/cert.pem).
        Extract on the Prometheus host with:
          tar -xz -C /etc/bridge_ssl/certs/
        """
        self.logger.trace(f"Request headers:{str(cherrypy.request.headers)}")
        self._validate_tls_config()
        job_suffix = self._parse_job_suffix(params)
        try:
            archive = self._build_archive(job_suffix)
        except OSError as exc:
            self.logger.error(MSG['CertFilesCopyError'].format('archive', exc))
            raise cherrypy.HTTPError(500, MSG['CertFilesCopyError'].format('archive', exc))
        self.logger.info(MSG['TlsCertsServed'].format(job_suffix))
        cherrypy.response.headers['Content-Type'] = 'application/gzip'
        cherrypy.response.headers['Content-Disposition'] = 'attachment; filename="tls_certs.tar.gz"'
        return archive

    def OPTIONS(self, **params):
        del cherrypy.response.headers['Allow']
        cherrypy.response.headers['Access-Control-Allow-Methods'] = 'GET, OPTIONS'
        cherrypy.response.headers['Access-Control-Allow-Origin'] = '*'
        cherrypy.response.headers['Access-Control-Allow-Headers'] = 'Content-Type,Accept'
        cherrypy.response.headers['Access-Control-Max-Age'] = 604800
